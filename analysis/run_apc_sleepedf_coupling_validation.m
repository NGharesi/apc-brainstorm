function results = run_apc_sleepedf_coupling_validation(dataDir, nSurrogates, profileName)
% RUN_APC_SLEEPEDF_COUPLING_VALIDATION
% Validate APC on human Sleep-EDF slow-wave--spindle coupling.
%
% This analysis deliberately gives APC and conventional PAC the same
% contiguous stage-specific signals, amplitude search range, and circular
% shift surrogate offsets. APC estimates its phase carrier without a
% manually supplied slow-wave band; PAC scans the specified slow range.
%
% USAGE
%   results = run_apc_sleepedf_coupling_validation
%   results = run_apc_sleepedf_coupling_validation(dataDir, nSurrogates)
%   results = run_apc_sleepedf_coupling_validation(dataDir, nSurrogates, 'wideband')
%
% INPUT
%   dataDir     Folder containing apc_sleepedf_*_PSG_results.mat files
%               generated by run_apc_sleepedf_batch.
%   nSurrogates Number of common circular-shift surrogates (default 100).
%
% OUTPUTS (written to dataDir)
%   apc_sleepedf_coupling_validation_narrowband_results.mat
%   apc_sleepedf_coupling_validation_narrowband_signal_level.csv
%   apc_sleepedf_coupling_validation_narrowband_summary.csv
%   apc_sleepedf_coupling_validation_narrowband_apc_vs_pac_tests.csv
%   apc_sleepedf_coupling_validation_narrowband_stage_tests.csv
%   apc_sleepedf_coupling_validation_narrowband_anterior_posterior_tests.csv
%   apc_sleepedf_coupling_validation_narrowband_summary.txt
%
% REQUIREMENTS
%   Signal Processing Toolbox (bandpass, hilbert, findpeaks) and bst_apc.m
%   on the MATLAB path. This runner calls bst_apc directly; it is not a
%   reimplementation of APC.

    if nargin < 1 || isempty(dataDir)
        dataDir = fileparts(mfilename('fullpath'));
    end
    if nargin < 2 || isempty(nSurrogates)
        nSurrogates = 100;
    end
    if nargin < 3 || isempty(profileName)
        profileName = 'narrowband';
    end
    if ~exist('bst_apc', 'file')
        error('bst_apc.m must be on the MATLAB path.');
    end

    cfg = local_config(nSurrogates, profileName);
    files = dir(fullfile(dataDir, 'apc_sleepedf_*_PSG_results.mat'));
    if isempty(files)
        error('No apc_sleepedf_*_PSG_results.mat files found in: %s', dataDir);
    end

    rng(cfg.random_seed, 'twister');
    rows = repmat(local_empty_row(), 0, 1);
    fprintf('Sleep-EDF APC coupling validation: %d recordings, %d surrogates each.\n', ...
        numel(files), cfg.n_surrogates);

    for iFile = 1:numel(files)
        if iFile == 1 || mod(iFile, 10) == 0 || iFile == numel(files)
            fprintf('  [%3d/%3d] %s\n', iFile, numel(files), files(iFile).name);
        end
        S = load(fullfile(files(iFile).folder, files(iFile).name), 'results');
        if ~isfield(S, 'results') || ~isfield(S.results, 'channels')
            warning('Skipping malformed result file: %s', files(iFile).name);
            continue;
        end
        recordingId = erase(files(iFile).name, 'apc_sleepedf_');
        recordingId = erase(recordingId, '_results.mat');
        % Sleep-EDF PSG names encode participant in the first five characters
        % (for example, SC400) and night in the following digit.
        participantId = extractBefore(string(recordingId), 6);
        rows = [rows; local_process_recording(S.results, string(recordingId), participantId, cfg)]; %#ok<AGROW>
    end

    signalTable = struct2table(rows);
    % Preserve the expensive per-recording computation before reporting/tests.
    outputPrefix = ['apc_sleepedf_coupling_validation_' cfg.profile_name];
    checkpointCsv = fullfile(dataDir, [outputPrefix '_signal_level.csv']);
    writetable(signalTable, checkpointCsv);
    summaryTable = local_summary_table(signalTable);
    comparisonTable = local_method_comparisons(signalTable, cfg);
    stageTable = local_within_tests(signalTable, 'stage', cfg);
    channelTable = local_within_tests(signalTable, 'channel', cfg);

    results = struct();
    results.config = cfg;
    results.signal_table = signalTable;
    results.summary_table = summaryTable;
    results.apc_vs_pac_tests = comparisonTable;
    results.stage_tests = stageTable;
    results.anterior_posterior_tests = channelTable;
    results.input_files = string(fullfile({files.folder}, {files.name}));

    results.output_mat = fullfile(dataDir, [outputPrefix '_results.mat']);
    results.output_signal_csv = checkpointCsv;
    results.output_summary_csv = fullfile(dataDir, [outputPrefix '_summary.csv']);
    results.output_comparison_csv = fullfile(dataDir, [outputPrefix '_apc_vs_pac_tests.csv']);
    results.output_stage_csv = fullfile(dataDir, [outputPrefix '_stage_tests.csv']);
    results.output_channel_csv = fullfile(dataDir, [outputPrefix '_anterior_posterior_tests.csv']);
    results.output_text = fullfile(dataDir, [outputPrefix '_summary.txt']);

    save(results.output_mat, 'results', '-v7.3');
    writetable(signalTable, results.output_signal_csv);
    writetable(summaryTable, results.output_summary_csv);
    writetable(comparisonTable, results.output_comparison_csv);
    writetable(stageTable, results.output_stage_csv);
    writetable(channelTable, results.output_channel_csv);
    local_write_summary(results.output_text, signalTable, summaryTable, comparisonTable, stageTable, channelTable, cfg);

    fprintf('\nSaved validation outputs:\n');
    fprintf('  %s\n', results.output_mat);
    fprintf('  %s\n', results.output_text);
end


function cfg = local_config(nSurrogates, profileName)
    cfg = struct();
    cfg.profile_name = char(lower(string(profileName)));
    cfg.channels = ["EEGFpz_Cz", "EEGPz_Oz"];
    cfg.stages = ["n2", "n3"];
    cfg.stage_labels = ["N2", "N3"];
    switch cfg.profile_name
        case 'narrowband'
            cfg.amp_search_hz = [6, 22];
        case 'wideband'
            % Prespecified shared range well beyond the 8-20 Hz spindle detector band.
            cfg.amp_search_hz = [4, 30];
        otherwise
            error('Unknown profile: %s. Use narrowband or wideband.', cfg.profile_name);
    end
    cfg.pac_phase_grid_hz = 0.5:0.25:2.0;
    cfg.pac_amp_grid_hz = cfg.amp_search_hz(1):1:cfg.amp_search_hz(2);
    cfg.pac_phase_half_width_hz = 0.25;
    cfg.pac_amp_half_width_hz = 2.0;
    cfg.detector_slow_band_hz = [0.5, 2.0];
    cfg.detector_sigma_band_hz = [10, 16];
    cfg.detector_spindle_peak_band_hz = [8, 20];
    cfg.n_surrogates = nSurrogates;
    cfg.min_shift_fraction = 0.10;
    cfg.max_shift_fraction = 0.90;
    cfg.boundary_tolerance_hz = 0.5;
    cfg.n_test_permutations = 10000;
    cfg.random_seed = 20260903;
end


function rows = local_process_recording(result, recordingId, participantId, cfg)
    rows = repmat(local_empty_row(), 0, 1);
    for iChannel = 1:numel(cfg.channels)
        channelName = cfg.channels(iChannel);
        if ~isfield(result.channels, char(channelName))
            continue;
        end
        channelResult = result.channels.(char(channelName));
        for iStage = 1:numel(cfg.stages)
            stageName = cfg.stages(iStage);
            if ~isfield(channelResult, char(stageName))
                continue;
            end
            stageResult = channelResult.(char(stageName));
            if ~isfield(stageResult, 'signal') || ~isfield(stageResult, 'time')
                continue;
            end
            signal = double(stageResult.signal(:));
            time = double(stageResult.time(:));
            if numel(signal) < 500 || numel(signal) ~= numel(time)
                continue;
            end
            fs = 1 ./ median(diff(time));
            if ~isfinite(fs) || fs <= 0
                continue;
            end
            signal = fillmissing(signal, 'linear', 'EndValues', 'nearest');
            signal = signal - mean(signal, 'omitnan');

            detector = local_independent_spindle_detector(signal, fs, cfg);
            shifts = local_common_shifts(numel(signal), cfg);
            apc = local_run_apc(signal, fs, shifts, cfg);
            pac = local_run_pac_scan(signal, fs, shifts, cfg);
            rows(end + 1, 1) = local_pack_row( ...
                participantId, recordingId, channelName, cfg.stage_labels(iStage), signal, fs, detector, apc, pac); %#ok<AGROW>
        end
    end
end


function detector = local_independent_spindle_detector(signal, fs, cfg)
    slow = local_bandpass(signal, fs, cfg.detector_slow_band_hz);
    slowPhase = angle(hilbert(slow));
    sigma = local_bandpass(signal, fs, cfg.detector_sigma_band_hz);
    sigmaEnv = smoothdata(abs(hilbert(sigma)), 'movmean', max(3, round(0.10 * fs)));
    events = local_detect_spindles(sigmaEnv, fs);

    eventPhases = nan(numel(events), 1);
    eventFreqs = nan(numel(events), 1);
    pad = round(0.25 * fs);
    for iEvent = 1:numel(events)
        eventPhases(iEvent) = slowPhase(events(iEvent).peak_idx);
        lo = max(1, events(iEvent).start_idx - pad);
        hi = min(numel(signal), events(iEvent).stop_idx + pad);
        eventFreqs(iEvent) = local_spectral_peak(signal(lo:hi), fs, cfg.detector_spindle_peak_band_hz);
    end
    validPhase = eventPhases(isfinite(eventPhases));
    if isempty(validPhase)
        preferredPhase = NaN;
        phaseR = NaN;
    else
        phaseVector = mean(exp(1i .* validPhase));
        preferredPhase = local_wrap180(rad2deg(angle(phaseVector)));
        phaseR = abs(phaseVector);
    end
    detector = struct( ...
        'slow_hz', local_spectral_peak(slow, fs, cfg.detector_slow_band_hz), ...
        'spindle_hz', median(eventFreqs, 'omitnan'), ...
        'preferred_phase_deg', preferredPhase, ...
        'phase_r', phaseR, ...
        'n_spindles', numel(events));
end


function events = local_detect_spindles(envelope, fs)
    thresholds = [mean(envelope, 'omitnan') + 1.5 * std(envelope, 0, 'omitnan'), ...
        mean(envelope, 'omitnan') + std(envelope, 0, 'omitnan'), ...
        prctile(envelope, 85), prctile(envelope, 80)];
    minLength = round(0.4 * fs);
    maxLength = round(2.5 * fs);
    events = repmat(struct('start_idx', NaN, 'stop_idx', NaN, 'peak_idx', NaN), 0, 1);
    for threshold = thresholds
        mask = envelope > threshold;
        edge = diff([false; mask; false]);
        starts = find(edge == 1);
        stops = find(edge == -1) - 1;
        for iSegment = 1:numel(starts)
            len = stops(iSegment) - starts(iSegment) + 1;
            if len < minLength || len > maxLength
                continue;
            end
            [~, atPeak] = max(envelope(starts(iSegment):stops(iSegment)));
            events(end + 1, 1) = struct( ...
                'start_idx', starts(iSegment), 'stop_idx', stops(iSegment), ...
                'peak_idx', starts(iSegment) + atPeak - 1); %#ok<AGROW>
        end
        if ~isempty(events)
            return;
        end
    end
end


function item = local_run_apc(signal, fs, shifts, cfg)
    time = (0:numel(signal) - 1) ./ fs;
    apcOptions = struct( ...
        'fA', cfg.amp_search_hz, ...
        'epoch', [-1.5, 1.5], ...
        'decomposition', 'fft_peak', ...
        'metric', 'canolty', ...
        'diagm', false, ...
        'surrogates', false, ...
        'num_perm', 0, ...
        'numPhaseBins', 18, ...
        'minPhaseHz', cfg.detector_slow_band_hz(1), ...
        'maxPhaseHz', cfg.detector_slow_band_hz(2));
    sApc = bst_apc(struct('data', signal(:).', 'time', time(:).'), apcOptions);

    item = local_empty_method_item();
    item.status = double(sApc.status_code.Value(1));
    item.fp_hz = double(sApc.phase_frequency_hz.Value(1));
    item.fa_hz = double(sApc.amplitude_frequency_hz.Value(1));
    item.preferred_phase_deg = double(sApc.preferred_phase_deg.Value(1));
    item.n_events = double(sApc.n_bursts.Value(1));
    if item.status ~= 0 || ~isfinite(item.fp_hz) || ~isfinite(item.fa_hz)
        return;
    end
    [phase, amp] = local_phase_amp(signal, fs, item.fp_hz, item.fa_hz, cfg);
    [item.score_raw, phaseFromMetric] = local_canolty(phase, amp);
    if ~isfinite(item.preferred_phase_deg)
        item.preferred_phase_deg = phaseFromMetric;
    end
    [item.score_z, item.score_percentile, item.null_mean, item.null_std] = ...
        local_surrogate_stats(phase, amp, item.score_raw, shifts);
    item.boundary_hit = local_boundary_hit(item.fa_hz, cfg);
end


function item = local_run_pac_scan(signal, fs, shifts, cfg)
    scoreMap = nan(numel(cfg.pac_phase_grid_hz), numel(cfg.pac_amp_grid_hz));
    phaseMap = cell(numel(cfg.pac_phase_grid_hz), 1);
    ampMap = cell(numel(cfg.pac_amp_grid_hz), 1);
    prefMap = nan(size(scoreMap));
    for iFp = 1:numel(cfg.pac_phase_grid_hz)
        fp = cfg.pac_phase_grid_hz(iFp);
        phaseMap{iFp} = angle(hilbert(local_bandpass(signal, fs, ...
            [max(0.5, fp - cfg.pac_phase_half_width_hz), min(2.0, fp + cfg.pac_phase_half_width_hz)])));
    end
    for iFa = 1:numel(cfg.pac_amp_grid_hz)
        fa = cfg.pac_amp_grid_hz(iFa);
        ampMap{iFa} = abs(hilbert(local_bandpass(signal, fs, ...
            [max(cfg.amp_search_hz(1), fa - cfg.pac_amp_half_width_hz), ...
             min(cfg.amp_search_hz(2), fa + cfg.pac_amp_half_width_hz)])));
    end
    for iFp = 1:numel(phaseMap)
        for iFa = 1:numel(ampMap)
            [scoreMap(iFp, iFa), prefMap(iFp, iFa)] = local_canolty(phaseMap{iFp}, ampMap{iFa});
        end
    end
    item = local_empty_method_item();
    [item.score_raw, atBest] = max(scoreMap(:), [], 'omitnan');
    if ~isfinite(item.score_raw)
        item.status = 1;
        return;
    end
    [iFp, iFa] = ind2sub(size(scoreMap), atBest);
    item.fp_hz = cfg.pac_phase_grid_hz(iFp);
    item.fa_hz = cfg.pac_amp_grid_hz(iFa);
    item.preferred_phase_deg = prefMap(iFp, iFa);
    item.status = 0;
    item.n_events = numel(signal);
    [item.score_z, item.score_percentile, item.null_mean, item.null_std] = ...
        local_surrogate_stats(phaseMap{iFp}, ampMap{iFa}, item.score_raw, shifts);
    item.boundary_hit = local_boundary_hit(item.fa_hz, cfg);
end


function [phase, amp] = local_phase_amp(signal, fs, fp, fa, cfg)
    phaseBand = [max(0.5, fp - cfg.pac_phase_half_width_hz), min(2.0, fp + cfg.pac_phase_half_width_hz)];
    ampBand = [max(cfg.amp_search_hz(1), fa - cfg.pac_amp_half_width_hz), ...
        min(cfg.amp_search_hz(2), fa + cfg.pac_amp_half_width_hz)];
    phase = angle(hilbert(local_bandpass(signal, fs, phaseBand)));
    amp = abs(hilbert(local_bandpass(signal, fs, ampBand)));
end


function [score, prefDeg] = local_canolty(phase, amp)
    keep = isfinite(phase) & isfinite(amp);
    phase = phase(keep);
    amp = amp(keep);
    if isempty(phase) || mean(amp) <= 0
        score = NaN;
        prefDeg = NaN;
        return;
    end
    vector = mean(amp .* exp(1i .* phase));
    score = abs(vector) ./ mean(amp);
    prefDeg = local_wrap180(rad2deg(angle(vector)));
end


function shifts = local_common_shifts(nSamples, cfg)
    lo = max(1, round(cfg.min_shift_fraction * nSamples));
    hi = max(lo + 1, round(cfg.max_shift_fraction * nSamples));
    shifts = randi([lo, hi], cfg.n_surrogates, 1);
end


function [z, percentile, nullMean, nullStd] = local_surrogate_stats(phase, amp, observed, shifts)
    nullScores = nan(numel(shifts), 1);
    for iShift = 1:numel(shifts)
        nullScores(iShift) = local_canolty(phase, circshift(amp, shifts(iShift)));
    end
    nullMean = mean(nullScores, 'omitnan');
    nullStd = std(nullScores, 0, 'omitnan');
    if isfinite(nullStd) && nullStd > 0
        z = (observed - nullMean) ./ nullStd;
    else
        z = NaN;
    end
    percentile = mean(observed > nullScores, 'omitnan');
end


function x = local_bandpass(signal, fs, band)
    nyquist = fs ./ 2;
    band = double(band(:).');
    band(1) = max(band(1), 0.01);
    band(2) = min(band(2), nyquist - 0.01);
    if band(2) <= band(1)
        x = zeros(size(signal));
        return;
    end
    x = bandpass(double(signal(:)), band, fs);
end


function peakHz = local_spectral_peak(signal, fs, band)
    signal = double(signal(:));
    if numel(signal) < 8 || all(~isfinite(signal))
        peakHz = NaN;
        return;
    end
    signal = signal - mean(signal, 'omitnan');
    n = numel(signal);
    power = abs(fft(signal)).^2;
    freqs = (0:floor(n ./ 2))' .* (fs ./ n);
    power = power(1:numel(freqs));
    keep = freqs >= band(1) & freqs <= band(2);
    if ~any(keep)
        peakHz = NaN;
        return;
    end
    localFreqs = freqs(keep);
    localPower = power(keep);
    [~, atPeak] = max(localPower);
    peakHz = localFreqs(atPeak);
end


function row = local_empty_row()
    row = struct( ...
        'participant_id', "", 'recording_id', "", 'channel', "", 'stage', "", ...
        'duration_s', NaN, 'n_samples', NaN, 'signal_std', NaN, ...
        'detector_slow_hz', NaN, 'detector_spindle_hz', NaN, ...
        'detector_preferred_phase_deg', NaN, 'detector_phase_resultant_r', NaN, ...
        'detector_n_spindles', NaN, ...
        'apc_status', NaN, 'apc_fp_hz', NaN, 'apc_fa_hz', NaN, ...
        'apc_preferred_phase_deg', NaN, 'apc_score_raw', NaN, 'apc_score_z', NaN, ...
        'apc_score_percentile', NaN, 'apc_null_mean', NaN, 'apc_null_std', NaN, ...
        'apc_boundary_hit', NaN, 'apc_n_events', NaN, ...
        'pac_status', NaN, 'pac_fp_hz', NaN, 'pac_fa_hz', NaN, ...
        'pac_preferred_phase_deg', NaN, 'pac_score_raw', NaN, 'pac_score_z', NaN, ...
        'pac_score_percentile', NaN, 'pac_null_mean', NaN, 'pac_null_std', NaN, ...
        'pac_boundary_hit', NaN, 'pac_n_events', NaN, ...
        'apc_fp_abs_err_hz', NaN, 'apc_fa_abs_err_hz', NaN, 'apc_phase_abs_err_deg', NaN, ...
        'pac_fp_abs_err_hz', NaN, 'pac_fa_abs_err_hz', NaN, 'pac_phase_abs_err_deg', NaN);
end


function row = local_pack_row(participantId, recordingId, channelName, stageName, signal, fs, detector, apc, pac)
    row = local_empty_row();
    row.participant_id = participantId;
    row.recording_id = recordingId;
    row.channel = channelName;
    row.stage = stageName;
    row.duration_s = numel(signal) ./ fs;
    row.n_samples = numel(signal);
    row.signal_std = std(signal, 0, 'omitnan');
    row.detector_slow_hz = detector.slow_hz;
    row.detector_spindle_hz = detector.spindle_hz;
    row.detector_preferred_phase_deg = detector.preferred_phase_deg;
    row.detector_phase_resultant_r = detector.phase_r;
    row.detector_n_spindles = detector.n_spindles;
    row = local_add_method(row, 'apc', apc, detector);
    row = local_add_method(row, 'pac', pac, detector);
end


function row = local_add_method(row, prefix, item, detector)
    row.([prefix '_status']) = item.status;
    row.([prefix '_fp_hz']) = item.fp_hz;
    row.([prefix '_fa_hz']) = item.fa_hz;
    row.([prefix '_preferred_phase_deg']) = item.preferred_phase_deg;
    row.([prefix '_score_raw']) = item.score_raw;
    row.([prefix '_score_z']) = item.score_z;
    row.([prefix '_score_percentile']) = item.score_percentile;
    row.([prefix '_null_mean']) = item.null_mean;
    row.([prefix '_null_std']) = item.null_std;
    row.([prefix '_boundary_hit']) = item.boundary_hit;
    row.([prefix '_n_events']) = item.n_events;
    row.([prefix '_fp_abs_err_hz']) = abs(item.fp_hz - detector.slow_hz);
    row.([prefix '_fa_abs_err_hz']) = abs(item.fa_hz - detector.spindle_hz);
    row.([prefix '_phase_abs_err_deg']) = local_circular_distance(item.preferred_phase_deg, detector.preferred_phase_deg);
end


function item = local_empty_method_item()
    item = struct('status', 1, 'fp_hz', NaN, 'fa_hz', NaN, ...
        'preferred_phase_deg', NaN, 'score_raw', NaN, 'score_z', NaN, ...
        'score_percentile', NaN, 'null_mean', NaN, 'null_std', NaN, ...
        'boundary_hit', NaN, 'n_events', NaN);
end


function tf = local_boundary_hit(faHz, cfg)
    tf = isfinite(faHz) && (abs(faHz - cfg.amp_search_hz(1)) <= cfg.boundary_tolerance_hz || ...
        abs(faHz - cfg.amp_search_hz(2)) <= cfg.boundary_tolerance_hz);
end


function T = local_summary_table(signalTable)
    methods = ["APC", "PAC"];
    rows = cell(0, 14);
    for method = methods
        % Dynamic table indexing requires a character vector in older MATLAB releases.
        prefix = char(lower(method));
        for channel = unique(signalTable.channel, 'stable').'
            for stage = unique(signalTable.stage, 'stable').'
                sub = signalTable(signalTable.channel == channel & signalTable.stage == stage, :);
                rows(end + 1, :) = {method, channel, stage, height(sub), ...
                    sum(sub.([prefix '_status']) == 0), ...
                    median(sub.([prefix '_score_z']), 'omitnan'), iqr(sub.([prefix '_score_z'])), ...
                    median(sub.([prefix '_fp_hz']), 'omitnan'), median(sub.([prefix '_fa_hz']), 'omitnan'), ...
                    median(sub.([prefix '_preferred_phase_deg']), 'omitnan'), ...
                    median(sub.([prefix '_fp_abs_err_hz']), 'omitnan'), ...
                    median(sub.([prefix '_fa_abs_err_hz']), 'omitnan'), ...
                    median(sub.([prefix '_phase_abs_err_deg']), 'omitnan'), ...
                    mean(sub.([prefix '_boundary_hit']), 'omitnan')}; %#ok<AGROW>
            end
        end
    end
    T = cell2table(rows, 'VariableNames', {'method','channel','stage','n_recordings','valid_n', ...
        'score_z_median','score_z_iqr','fp_median_hz','fa_median_hz','phase_median_deg', ...
        'fp_abs_err_median_hz','fa_abs_err_median_hz','phase_abs_err_median_deg','boundary_hit_rate'});
end


function T = local_method_comparisons(signalTable, cfg)
    metrics = ["fp_abs_err_hz", "fa_abs_err_hz", "phase_abs_err_deg", "score_z", "boundary_hit"];
    directions = ["lower", "lower", "lower", "higher", "lower"];
    rows = cell(0, 12);
    for channel = unique(signalTable.channel, 'stable').'
        for stage = unique(signalTable.stage, 'stable').'
            sub = signalTable(signalTable.channel == channel & signalTable.stage == stage, :);
            for iMetric = 1:numel(metrics)
                metric = metrics(iMetric);
                a = sub.(['apc_' char(metric)]);
                p = sub.(['pac_' char(metric)]);
                keep = isfinite(a) & isfinite(p);
                a = a(keep); p = p(keep);
                if directions(iMetric) == "lower"
                    diff = p - a; % Positive means lower APC error / boundary rate.
                else
                    diff = a - p; % Positive means higher APC score.
                end
                [pValue, ciLow, ciHigh] = local_sign_flip(diff, cfg);
                rows(end + 1, :) = {channel, stage, metric, directions(iMetric), numel(diff), ...
                    median(a, 'omitnan'), median(p, 'omitnan'), mean(diff, 'omitnan'), ...
                    ciLow, ciHigh, pValue, mean(diff > 0, 'omitnan')}; %#ok<AGROW>
            end
        end
    end
    T = cell2table(rows, 'VariableNames', {'channel','stage','metric','direction','n_pairs', ...
        'apc_median','pac_median','preferred_signed_mean_diff','ci_low','ci_high','p_two_sided','apc_better_fraction'});
end


function T = local_within_tests(signalTable, mode, cfg)
    if strcmp(mode, 'stage')
        fixedValues = unique(signalTable.channel, 'stable');
        leftKey = "N2"; rightKey = "N3"; groupField = 'channel'; keyField = 'stage';
        metrics = ["detector_spindle_hz", "apc_fp_hz", "apc_fa_hz", "apc_score_z", "apc_fa_abs_err_hz", "pac_fa_abs_err_hz"];
        signs = [1, 1, 1, 1, -1, -1];
        comparisonLabel = "N3-minus-N2";
    else
        fixedValues = unique(signalTable.stage, 'stable');
        leftKey = "EEGFpz_Cz"; rightKey = "EEGPz_Oz"; groupField = 'stage'; keyField = 'channel';
        metrics = ["detector_spindle_hz", "apc_fa_hz", "pac_fa_hz", "apc_score_z", "apc_fa_abs_err_hz", "pac_fa_abs_err_hz"];
        signs = [1, 1, 1, 1, -1, -1];
        comparisonLabel = "posterior-minus-anterior";
    end
    rows = cell(0, 11);
    for fixed = fixedValues.'
        sub = signalTable(signalTable.(groupField) == fixed, :);
        ids = unique(sub.recording_id, 'stable');
        for iMetric = 1:numel(metrics)
            left = nan(numel(ids), 1); right = left;
            for iId = 1:numel(ids)
                pair = sub(sub.recording_id == ids(iId), :);
                l = pair{pair.(keyField) == leftKey, char(metrics(iMetric))};
                r = pair{pair.(keyField) == rightKey, char(metrics(iMetric))};
                if ~isempty(l), left(iId) = l(1); end
                if ~isempty(r), right(iId) = r(1); end
            end
            keep = isfinite(left) & isfinite(right);
            left = left(keep); right = right(keep);
            diff = signs(iMetric) .* (right - left);
            [pValue, ciLow, ciHigh] = local_sign_flip(diff, cfg);
            rows(end + 1, :) = {fixed, comparisonLabel, metrics(iMetric), numel(diff), ...
                median(left, 'omitnan'), median(right, 'omitnan'), mean(diff, 'omitnan'), ...
                ciLow, ciHigh, pValue, mean(diff > 0, 'omitnan')}; %#ok<AGROW>
        end
    end
    T = cell2table(rows, 'VariableNames', {groupField,'comparison','metric','n_pairs', ...
        'left_median','right_median','preferred_signed_mean_diff','ci_low','ci_high','p_two_sided','right_gt_left_fraction'});
end


function [pValue, ciLow, ciHigh] = local_sign_flip(diff, cfg)
    diff = diff(isfinite(diff));
    if isempty(diff)
        pValue = NaN; ciLow = NaN; ciHigh = NaN;
        return;
    end
    observed = mean(diff);
    n = numel(diff);
    signs = 2 .* (rand(cfg.n_test_permutations, n) > 0.5) - 1;
    nullMeans = mean(signs .* diff.', 2);
    % Add-one correction prevents impossible p = 0 reports from finite permutations.
    pValue = (sum(abs(nullMeans) >= abs(observed)) + 1) ./ (cfg.n_test_permutations + 1);
    bootIdx = randi(n, cfg.n_test_permutations, n);
    bootMeans = mean(diff(bootIdx), 2);
    ci = prctile(bootMeans, [2.5, 97.5]);
    ciLow = ci(1); ciHigh = ci(2);
end


function local_write_summary(filename, signalTable, summaryTable, comparisonTable, stageTable, channelTable, cfg)
    fid = fopen(filename, 'w');
    if fid < 0, error('Could not write %s', filename); end
    cleaner = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fprintf(fid, 'Sleep-EDF slow-wave-spindle coupling validation\n');
    fprintf(fid, 'Recordings analyzed: %d\n', numel(unique(signalTable.recording_id)));
    fprintf(fid, 'Signal entries analyzed: %d\n', height(signalTable));
    fprintf(fid, 'APC amplitude search shared across all channels/stages: %.1f-%.1f Hz\n', cfg.amp_search_hz);
    fprintf(fid, 'PAC grid: phase %.2f:%.2f:%.2f Hz; amplitude %.1f:%.1f:%.1f Hz\n\n', ...
        cfg.pac_phase_grid_hz(1), cfg.pac_phase_grid_hz(2) - cfg.pac_phase_grid_hz(1), cfg.pac_phase_grid_hz(end), ...
        cfg.pac_amp_grid_hz(1), cfg.pac_amp_grid_hz(2) - cfg.pac_amp_grid_hz(1), cfg.pac_amp_grid_hz(end));
    fprintf(fid, 'Method summary\n');
    for i = 1:height(summaryTable)
        r = summaryTable(i, :);
        fprintf(fid, '%s | %s | %s | z=%.3f | fP err=%.3f Hz | fA err=%.3f Hz | phase err=%.1f deg | boundary=%.1f%%\n', ...
            r.method, r.channel, r.stage, r.score_z_median, r.fp_abs_err_median_hz, r.fa_abs_err_median_hz, ...
            r.phase_abs_err_median_deg, 100 .* r.boundary_hit_rate);
    end
    local_write_test_section(fid, 'APC versus PAC paired tests', comparisonTable);
    local_write_test_section(fid, 'Stage tests', stageTable);
    local_write_test_section(fid, 'Anterior-posterior tests', channelTable);
end


function local_write_test_section(fid, label, T)
    fprintf(fid, '\n%s\n', label);
    for i = 1:height(T)
        r = T(i, :);
        fprintf(fid, '%s | %s | %s | n=%d | preferred difference=%.4f | 95%% CI [%.4f, %.4f] | p=%.4g\n', ...
            string(r{1, 1}), string(r{1, 2}), string(r.metric), r.n_pairs, ...
            r.preferred_signed_mean_diff, r.ci_low, r.ci_high, r.p_two_sided);
    end
end


function value = local_wrap180(value)
    value = mod(value + 180, 360) - 180;
end


function distance = local_circular_distance(a, b)
    if ~isfinite(a) || ~isfinite(b)
        distance = NaN;
    else
        distance = abs(local_wrap180(a - b));
    end
end
