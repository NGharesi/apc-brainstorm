function rd_export_comparison(d)
% Compare original MAT doubles, then emit round-trip (17-digit) CSV values.
root=fileparts(fileparts(d));out=fullfile(d,'results');combined=table();savedAll=struct();
for benchmark=["sparsity","distractor"]
 if benchmark=="sparsity"
  savedFile='apc_burst_sparsity_benchmark_full.mat';levelName='burst_keep_rate';
 else
  savedFile='apc_distractor_frequency_benchmark_reviewer_control.mat';levelName='distractor_scale';
 end
 saved=load(fullfile(root,savedFile),'runTable');st=saved.runTable;
 st=st(string(st.method)=="APC",:);assert(height(st)==175);
 savedAll.(benchmark)=st;
 obs=load(fullfile(out,char('checkpoint_'+benchmark+'.mat')),'rows');
 rt=struct2table([obs.rows{:}]);assert(height(rt)==175);
 T=table();
 for i=1:height(rt)
  s=st(abs(st.(levelName)-rt.level(i))<1e-12 & st.repeat_index==rt.repeat_index(i),:);assert(height(s)==1);
  a=struct('benchmark',benchmark,'level',rt.level(i),'repeat_index',rt.repeat_index(i), ...
   'saved_fA_hz',s.recovered_fa_hz,'reproduced_fA_hz',rt.reproduced_fa_hz(i), ...
   'saved_minus_reproduced_fA_hz',s.recovered_fa_hz-rt.reproduced_fa_hz(i), ...
   'saved_C_APC',s.score,'reproduced_C_APC',rt.reproduced_C_APC(i), ...
   'saved_minus_reproduced_C_APC',s.score-rt.reproduced_C_APC(i), ...
   'saved_fP_hz',s.recovered_fp_hz,'reproduced_fP_hz',rt.reproduced_fp_hz(i), ...
   'saved_minus_reproduced_fP_hz',s.recovered_fp_hz-rt.reproduced_fp_hz(i), ...
   'fA_exact_equal',s.recovered_fa_hz==rt.reproduced_fa_hz(i), ...
   'C_APC_exact_equal',s.score==rt.reproduced_C_APC(i), ...
   'fP_exact_equal',s.recovered_fp_hz==rt.reproduced_fp_hz(i), ...
   'fA_equal_within_1e_7_Hz',abs(s.recovered_fa_hz-rt.reproduced_fa_hz(i))<=1e-7, ...
   'C_APC_equal_within_1e_12',abs(s.score-rt.reproduced_C_APC(i))<=1e-12, ...
   'fP_equal_within_1e_7_Hz',abs(s.recovered_fp_hz-rt.reproduced_fp_hz(i))<=1e-7, ...
   'saved_fA_within_8_Hz_of_120',abs(s.recovered_fa_hz-120)<=8, ...
   'reproduced_fA_within_8_Hz_of_120',abs(rt.reproduced_fa_hz(i)-120)<=8, ...
   'saved_joint_recovery',abs(s.recovered_fa_hz-120)<=8 && abs(s.recovered_fp_hz-8)<=1, ...
   'reproduced_joint_recovery',abs(rt.reproduced_fa_hz(i)-120)<=8 && abs(rt.reproduced_fp_hz(i)-8)<=1, ...
   'saved_selection_route',"not_recorded",'reproduced_selection_route',rt.selection_route(i), ...
   'reproduced_status_code',rt.status_code(i));
  T=[T;struct2table(a)]; %#ok<AGROW>
 end
 combined=[combined;T]; %#ok<AGROW>
end
local_write17(combined,fullfile(d,'per_trial_comparison.csv'));
save(fullfile(out,'per_trial_comparison_full_precision.mat'),'combined','-v7');
for candidateKind=["historical_candidate","historical_clipped_candidate"]
candidate=load(fullfile(out,char(candidateKind+'_endpoint.mat')),'rows');ct=struct2table([candidate.rows{:}]);assert(height(ct)==25);
st=savedAll.sparsity;st=st(abs(st.burst_keep_rate-.15)<1e-12,:);C=table();
for i=1:height(ct)
 s=st(st.repeat_index==ct.repeat_index(i),:);
 a=struct('repeat_index',ct.repeat_index(i),'saved_fA_hz',s.recovered_fa_hz,'candidate_fA_hz',ct.candidate_fa_hz(i), ...
 'saved_C_APC',s.score,'candidate_C_APC',ct.candidate_C_APC(i), ...
 'saved_fP_hz',s.recovered_fp_hz,'candidate_fP_hz',ct.candidate_fp_hz(i), ...
 'fA_exact_equal',s.recovered_fa_hz==ct.candidate_fa_hz(i),'fP_exact_equal',s.recovered_fp_hz==ct.candidate_fp_hz(i), ...
 'C_APC_exact_equal',s.score==ct.candidate_C_APC(i),'C_APC_equal_within_1e_12',abs(s.score-ct.candidate_C_APC(i))<=1e-12, ...
 'candidate_joint_recovery',abs(ct.candidate_fa_hz(i)-120)<=8 && abs(ct.candidate_fp_hz(i)-8)<=1, ...
 'selection_route',ct.selection_route(i));
 C=[C;struct2table(a)]; %#ok<AGROW>
end
local_write17(C,fullfile(d,char(candidateKind+'_comparison.csv')));
end
fprintf('EXPORTED %d baseline paired trials and %d historical-candidate trials from MAT doubles.\n',height(combined),height(C));
end
function local_write17(T,file)
f=fopen(file,'w');cleanup=onCleanup(@() fclose(f)); %#ok<NASGU>
fprintf(f,'%s\n',strjoin(T.Properties.VariableNames,','));
for i=1:height(T)
 for j=1:width(T)
  if j>1,fprintf(f,',');end
  v=T{i,j};
  if isnumeric(v)||islogical(v),fprintf(f,'%.17g',double(v));else,fprintf(f,'%s',string(v));end
 end
 fprintf(f,'\n');
end
end
